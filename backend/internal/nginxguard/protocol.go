// Package nginxguard manages Nginx through a restricted, one-shot root command.
// Requests contain structured data, never configuration text or commands.
package nginxguard

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"net/netip"
	"regexp"
	"sort"
	"strings"
	"time"
)

type Rule struct {
	SiteID    int64  `json:"site_id"`
	Network   string `json:"network"`
	Kind      string `json:"kind"`
	ExpiresAt string `json:"expires_at"`
}
type Tenant struct {
	Default bool     `json:"default"`
	ID      int64    `json:"id"`
	Hosts   []string `json:"hosts"`
	Paths   []string `json:"paths"`
}
type Snapshot struct {
	Tenants []Tenant `json:"tenants"`
	Rules   []Rule   `json:"rules"`
}
type Result struct {
	Digest    string `json:"digest"`
	AppliedAt string `json:"applied_at"`
	Error     string `json:"error,omitempty"`
}
type LogEvent struct {
	Time   string `json:"time"`
	IP     string `json:"ip"`
	Host   string `json:"host"`
	Path   string `json:"path"`
	Status int    `json:"status"`
}
type LogBatch struct {
	Cursor string     `json:"cursor"`
	Items  []LogEvent `json:"items"`
}

func Digest(s Snapshot) string {
	b, _ := json.Marshal(s)
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

var hostPattern = regexp.MustCompile(`^[a-z0-9][a-z0-9.-]*[a-z0-9]$|^[a-z0-9]$|^\[[0-9a-f:]+\]$`)
var scanPathPattern = regexp.MustCompile(`^/[a-zA-Z0-9_./%+@:-]+\*?$`)

func ValidScanPath(value string) bool {
	return len(value) <= 256 && scanPathPattern.MatchString(value) && value != "/*"
}

func Validate(s Snapshot) error {
	if len(s.Tenants) > 500 || len(s.Rules) > 10000 {
		return errors.New("名单或站点数量超出上限")
	}
	ids := map[int64]bool{0: true}
	hosts := map[string]int64{}
	for _, t := range s.Tenants {
		if t.ID <= 0 || ids[t.ID] || len(t.Hosts) > 200 || len(t.Paths) > 100 {
			return errors.New("站点数据无效")
		}
		ids[t.ID] = true
		for _, h := range t.Hosts {
			if len(h) > 253 || !hostPattern.MatchString(strings.TrimPrefix(h, "*.")) {
				return errors.New("域名无效")
			}
			if previous, exists := hosts[h]; exists && previous != t.ID {
				return errors.New("多个站点的域名重复")
			}
			hosts[h] = t.ID
		}
		for _, p := range t.Paths {
			if !ValidScanPath(p) {
				return errors.New("扫描路径无效")
			}
		}
	}
	for _, r := range s.Rules {
		p, err := netip.ParsePrefix(r.Network)
		if err != nil || p != p.Masked() || p.Addr().Is4In6() || !ids[r.SiteID] || (r.Kind != "allow" && r.Kind != "deny") {
			return errors.New("IP 规则无效")
		}
		if r.ExpiresAt != "" {
			if _, err := time.Parse(time.RFC3339, r.ExpiresAt); err != nil {
				return errors.New("到期时间无效")
			}
		}
	}
	return nil
}

// Render uses geo for CIDR lookup and host maps for tenant isolation. Global
// allow > global deny > tenant allow > tenant deny is shared with the Go guard.
func Render(s Snapshot, now time.Time, logPath string) (string, string, error) {
	if err := Validate(s); err != nil {
		return "", "", err
	}
	var out strings.Builder
	out.WriteString("# Generated by GoCMS.\n")
	ids := []int64{0}
	for _, t := range s.Tenants {
		ids = append(ids, t.ID)
	}
	for _, id := range ids {
		for _, kind := range []string{"allow", "deny"} {
			fmt.Fprintf(&out, "geo $gocms_security_%d_%s {\n    default 0;\n", id, kind)
			networks := map[string]bool{}
			for _, r := range s.Rules {
				if r.SiteID != id || r.Kind != kind {
					continue
				}
				if r.ExpiresAt != "" {
					at, _ := time.Parse(time.RFC3339, r.ExpiresAt)
					if !at.After(now) {
						continue
					}
				}
				networks[r.Network] = true
			}
			keys := []string{}
			for n := range networks {
				keys = append(keys, n)
			}
			sort.Strings(keys)
			for _, n := range keys {
				fmt.Fprintf(&out, "    %s 1;\n", n)
			}
			out.WriteString("}\n")
		}
	}
	for _, kind := range []string{"allow", "deny"} {
		fallback := "0"
		for _, t := range s.Tenants {
			if t.Default {
				fallback = fmt.Sprintf("$gocms_security_%d_%s", t.ID, kind)
			}
		}
		fmt.Fprintf(&out, "map $host $gocms_security_site_%s {\n    default %s;\n", kind, fallback)
		for _, t := range s.Tenants {
			for _, h := range t.Hosts {
				if strings.HasPrefix(h, "*.") {
					fmt.Fprintf(&out, "    \"~^.+%s$\" $gocms_security_%d_%s;\n", regexp.QuoteMeta(h[1:]), t.ID, kind)
				} else {
					fmt.Fprintf(&out, "    %s $gocms_security_%d_%s;\n", h, t.ID, kind)
				}
			}
		}
		out.WriteString("}\n")
	}
	out.WriteString("map \"$gocms_security_0_allow:$gocms_security_0_deny:$gocms_security_site_allow:$gocms_security_site_deny\" $gocms_security_block {\n    default 0;\n    ~^0:1: 1;\n    0:0:0:1 1;\n}\n")
	out.WriteString("map $uri $gocms_security_scan {\n    default 0;\n")
	paths := map[string]bool{}
	for _, t := range s.Tenants {
		for _, p := range t.Paths {
			paths[p] = true
		}
	}
	keys := []string{}
	for p := range paths {
		keys = append(keys, p)
	}
	sort.Strings(keys)
	for _, p := range keys {
		pattern := regexp.QuoteMeta(strings.TrimSuffix(p, "*"))
		if !strings.HasSuffix(p, "*") {
			pattern += "$"
		}
		fmt.Fprintf(&out, "    \"~*^%s\" 1;\n", pattern)
	}
	out.WriteString("}\nmap \"$gocms_security_scan:$upstream_addr\" $gocms_security_log {\n    default 0;\n    \"1:\" 1;\n}\n")
	out.WriteString("log_format gocms_security escape=json '{\"time\":\"$time_iso8601\",\"ip\":\"$remote_addr\",\"host\":\"$host\",\"path\":\"$uri\",\"status\":$status}';\n")
	server := fmt.Sprintf("# Generated by GoCMS.\nif ($gocms_security_block) { return 403; }\nproxy_set_header X-Forwarded-Host $host;\naccess_log %s gocms_security if=$gocms_security_log;\n", logPath)
	return out.String(), server, nil
}
